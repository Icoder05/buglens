"""Assemble the cited onboarding guide (Markdown) — FR-S7.

Concept: the guide is a deterministic template filled with two kinds of
content. Structure (architecture, entry points, key classes, reading order,
glossary, statistics) comes straight from static analysis — no LLM. Prose
(overview, package summaries) comes from the LLM but only as validated
sentences, each followed by GitHub permalinks pinned to the analysed commit,
so a reader can click through to the exact line that supports every claim.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from buglens.analysis.code_graph import unresolved_total
from buglens.analysis.repo_analysis import RepoAnalysis
from buglens.config import Config
from buglens.onboard.summarize import ranked_packages
from buglens.retrieval.tokenize_code import STOPWORDS, split_identifier

GENERIC_NAMES = {"get", "set", "init", "new", "call", "str", "repr", "test", "self", "args",
                 "kwargs", "value", "name", "data", "func", "obj", "base", "main", "run"}


def permalink(repo: str, commit: str, path: str, line: int) -> str:
    return f"https://github.com/{repo}/blob/{commit}/{path}#L{line}"


def cite(repo: str, commit: str, citations: list[dict]) -> str:
    return " ".join(f"[`{c['path']}:{c['line']}`]({permalink(repo, commit, c['path'], c['line'])})"
                    for c in citations)


def key_classes(a: RepoAnalysis, n: int = 10) -> list[str]:
    g = a.graphs.inheritance
    return sorted(g.nodes, key=lambda c: (-g.in_degree(c), c))[:n]


def first_files(a: RepoAnalysis, n: int = 5) -> list[str]:
    """Top modules by PageRank among modules reachable (via imports) from entry points."""
    import networkx as nx

    g = a.graphs
    starts = [m for m in sorted(g.entry_modules) if m in g.imports]
    reachable = set()
    for m in starts:
        reachable |= {m} | nx.descendants(g.imports, m)
    pool = reachable or set(g.imports.nodes)
    return sorted(pool, key=lambda m: (-g.pagerank.get(m, 0.0), m))[:n]


def glossary(a: RepoAnalysis, n: int = 20) -> list[dict]:
    """Most frequent name parts across class/function names, each tied to a definition."""
    counts: Counter = Counter()
    defs: list[tuple[str, str, int, float, str]] = []  # (name, path, line, pr, kind)
    for f in a.facts.values():
        pr = a.graphs.pagerank.get(f.module, 0.0)
        for c in f.classes:
            defs.append((c["name"].split(".")[-1], f.path, c["start_line"], pr, "class"))
        for fn in f.functions:
            defs.append((fn["name"], f.path, fn["start_line"], pr, "function"))
        for c in f.classes:
            for m in c["methods"]:
                defs.append((m["name"], f.path, m["start_line"], pr, "method"))
    for name, *_ in defs:
        for part in {p.lower() for p in split_identifier(name)}:
            if len(part) >= 3 and part not in STOPWORDS and part not in GENERIC_NAMES:
                counts[part] += 1
    out = []
    for term, freq in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:n]:
        exact = [d for d in defs if d[0].lower() == term and d[4] == "class"]
        partial = [d for d in defs if term in {p.lower() for p in split_identifier(d[0])}]
        best = sorted(exact or partial, key=lambda d: (d[4] != "class", -d[3], d[1], d[2]))[0]
        out.append({"term": term, "count": freq, "name": best[0], "path": best[1],
                    "line": best[2], "kind": best[4]})
    return out


def build_guide(cfg: Config, a: RepoAnalysis, summaries: dict | None, diagrams: dict,
                out_dir: Path) -> str:
    repo, commit = a.repo, a.commit
    g = a.graphs
    md: list[str] = [f"# Onboarding guide: {repo}", "",
                     f"Generated by BugLens at commit [`{commit[:10]}`]"
                     f"(https://github.com/{repo}/tree/{commit}). Structure is from static "
                     "analysis; prose sentences are LLM-written and each is checked against "
                     "the cited lines.", ""]

    # 1. Overview
    md += ["## 1. Overview", ""]
    overview = (summaries or {}).get("overview") or []
    if overview:
        for s in overview:
            md.append(f"- {s['text']} {cite(repo, commit, s['citations'])}")
    else:
        md.append("_No validated overview yet (run `buglens summarize` with a Gemini key)._")
    md.append("")

    # 2. Architecture
    md += ["## 2. Architecture", "", "![Architecture block diagram](diagrams/block.svg)", "",
           "<details><summary>Mermaid source</summary>", "", "```mermaid",
           (out_dir / "diagrams" / "block.mmd").read_text(encoding="utf-8").rstrip(), "```", "",
           "</details>", ""]

    # 3. Entry points
    md += ["## 3. Entry points", ""]
    if a.entry_points:
        for e in a.entry_points[:20]:
            link = f"[`{e['path']}:{e['line']}`]({permalink(repo, commit, e['path'], e['line'])})"
            flow = diagrams.get("callflow", {}).get(e["name"])
            extra = f" — [call flow]({flow})" if flow else ""
            md.append(f"- **{e['kind']}** `{e['name']}` {link}{extra}")
    else:
        md.append("_No entry points detected (library-only package)._")
    md.append("")

    # 4. Core packages
    md += ["## 4. Core packages", "", "Top 10 packages by import-graph PageRank.", ""]
    by_pkg = {p["package"]: p for p in (summaries or {}).get("packages", [])}
    for pkg in ranked_packages(a, cfg.analysis.pkg_depth)[:10]:
        link = diagrams.get("packages", {}).get(pkg)
        title = f"### `{pkg}`" + (f" — [drill-down diagram]({link})" if link else "")
        md += [title, ""]
        sents = by_pkg.get(pkg, {}).get("sentences", [])
        if sents:
            for s in sents:
                md.append(f"- {s['text']} {cite(repo, commit, s['citations'])}")
        else:
            md.append("_No validated summary for this package._")
        md.append("")

    # 5. Key classes
    md += ["## 5. Key classes", "", "Top 10 classes by number of in-repo subclasses.", "",
           "| Class | Subclasses | Defined at | Diagram |", "| --- | --- | --- | --- |"]
    for c in key_classes(a):
        d = g.inheritance.nodes[c]
        link = diagrams.get("classes", {}).get(d["module"])
        module = d["module"]
        diagram = f"[classes of {module}]({link})" if link else ""
        where = f"[`{d['path']}:{d['line']}`]({permalink(repo, commit, d['path'], d['line'])})"
        md.append(f"| `{d['name']}` | {g.inheritance.in_degree(c)} | {where} | {diagram} |")
    md.append("")

    # 6. First files
    md += ["## 6. First 5 files to read", "",
           "Most central modules (PageRank) reachable from the entry points.", ""]
    for i, m in enumerate(first_files(a), start=1):
        path = g.module_path[m]
        md.append(f"{i}. [`{path}`]({permalink(repo, commit, path, 1)}) — `{m}`")
    md.append("")

    # 7. Glossary
    md += ["## 7. Glossary", "", "Most frequent name parts across class/function names "
           "(no LLM), each with a representative definition.", "",
           "| Term | Names using it | Definition |", "| --- | --- | --- |"]
    for t in glossary(a):
        md.append(f"| **{t['term']}** | {t['count']} | `{t['name']}` ({t['kind']}) "
                  f"[`{t['path']}:{t['line']}`]({permalink(repo, commit, t['path'], t['line'])}) |")
    md.append("")

    # 8. Stats
    faith = diagrams.get("faithfulness", {})
    st = (summaries or {}).get("stats", {})
    md += ["## 8. Generation stats", "",
           f"- Commit: `{commit}`",
           f"- Files analysed: {len(a.facts)} (parse failures: {a.parse_failures})",
           f"- Import graph: {g.imports.number_of_nodes()} modules, "
           f"{g.imports.number_of_edges()} edges",
           f"- Inheritance graph: {g.inheritance.number_of_nodes()} classes, "
           f"{g.inheritance.number_of_edges()} edges",
           f"- Call graph: {g.calls.number_of_nodes()} nodes, {g.calls.number_of_edges()} "
           f"resolved edges, {unresolved_total(g)} unresolved calls",
           f"- Diagrams: {faith.get('diagrams', 0)} generated, "
           f"{faith.get('verified_pct', 0):.1f}% of nodes/edges verified against the graphs",
           f"- Summary sentences: {st.get('kept', 0)} kept, {st.get('dropped', 0)} dropped by "
           f"the citation validator (model: {(summaries or {}).get('model', 'n/a')})", ""]
    return "\n".join(md)


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1), encoding="utf-8")
